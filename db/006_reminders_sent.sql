-- ============================================================
-- 006_reminders_sent.sql — защита от бесконечных повторов push
--
-- ЗАЧЕМ. Функция send-reminders выбирала напоминания по условию
-- «не отмечено выполненным и время уже близко», без нижней границы
-- и без отметки об отправке. Поэтому каждое просроченное и не снятое
-- галочкой напоминание уходило в телефон СНОВА КАЖДЫЕ 10 МИНУТ —
-- бесконечно. Пара таких напоминаний за неделю превращает уведомления
-- в шум, который отключают вместе со всеми остальными.
--
-- Добавляем отметку sent_at: отправили один раз — больше не трогаем.
--
-- КАК ПРИМЕНИТЬ: Supabase → SQL Editor → New query → вставить → Run.
-- После этого обновить код Edge Function send-reminders (в репозитории
-- он уже исправлен) и передеплоить её.
-- ============================================================

alter table public.reminders
  add column if not exists sent_at timestamptz;

comment on column public.reminders.sent_at is
  'Когда по этому напоминанию был отправлен push. Заполнено — повторно не шлём.';

-- Выборка «что пора отправить» должна быть быстрой
create index if not exists reminders_pending_push_idx
  on public.reminders (remind_at)
  where sent_at is null and done_at is null;

-- Старые напоминания, созданные до этой миграции, помечаем отправленными,
-- чтобы после включения исправленной функции они не хлынули все разом.
update public.reminders
   set sent_at = now()
 where sent_at is null
   and remind_at < now();

notify pgrst, 'reload schema';
